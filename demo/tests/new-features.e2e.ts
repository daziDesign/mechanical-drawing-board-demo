test('coordinate axes toggle, persist locally, and stay out of SVG export', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('button', { name: '新建空白画板' }).click();
  await expect(page.locator('.coordinate-axes')).toHaveCount(0);
  await page.getByRole('button', { name: '坐标轴 关' }).click();
  await expect(page.locator('.coordinate-axes')).toBeVisible();
  await expect(page.locator('.coordinate-axes text')).toContainText(['X', 'Y']);
  await expect(page.getByText('已保存', { exact: true })).toBeVisible();
  await page.reload();
  await expect(page.locator('.coordinate-axes')).toBeVisible();
  await page.getByRole('button', { name: '文件菜单' }).click();
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: '导出 SVG' }).click();
  const path = await (await download).path();
  if (!path) throw new Error('SVG 下载路径缺失');
  const svg = readFileSync(path, 'utf8');
  expect(svg).not.toContain('coordinate-axes');
  expect(svg).not.toContain('>X</text>');
});

test('teacher ink can be drawn, partly erased, replayed, restored, and exported', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('button', { name: '新建空白画板' }).click();
  const canvas = page.locator('svg.drawing-canvas');
  const box = await canvas.boundingBox();
  if (!box) throw new Error('画布未显示');
  const at = (x: number, y: number) => ({ x: box.x + box.width / 2 + x * 6, y: box.y + box.height / 2 - y * 6 });
  await page.getByRole('button', { name: '标注画笔' }).click();
  await page.getByRole('button', { name: '蓝色' }).click();
  await page.mouse.move(at(-20, 0).x, at(-20, 0).y);
  await page.mouse.down();
  await page.mouse.move(at(20, 0).x, at(20, 0).y, { steps: 12 });
  await page.mouse.up();
  await expect(canvas.locator('path[data-shape-id]')).toHaveCount(1);
  await expect(canvas.locator('path[data-shape-id]')).toHaveAttribute('stroke', '#287ee4');
  await page.screenshot({ path: 'qa/new-ink.png', fullPage: true });
  await page.getByRole('button', { name: '橡皮擦' }).click();
  await page.mouse.click(at(0, 0).x, at(0, 0).y);
  await expect(canvas.locator('path[data-shape-id]')).toHaveCount(2);
  await page.getByRole('button', { name: '撤销' }).click();
  await expect(canvas.locator('path[data-shape-id]')).toHaveCount(1);
  await page.getByRole('button', { name: '重做' }).click();
  await expect(canvas.locator('path[data-shape-id]')).toHaveCount(2);
  await expect(page.getByText('已保存', { exact: true })).toBeVisible();
  await page.reload();
  await expect(canvas.locator('path[data-shape-id]')).toHaveCount(2);
  await page.getByRole('button', { name: '文件菜单' }).click();
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: '导出 SVG' }).click();
  const path = await (await download).path();
  if (!path) throw new Error('SVG 下载路径缺失');
  expect(readFileSync(path, 'utf8')).toContain('stroke="#287ee4"');
});

